def _render_grouped(title: str, groups: list, prefix: str) -> str:
    lines = [title]
    for category, items in groups:
        lines.append(f"\n【{category}】")
        for command, desc in items:
            lines.append(f"{prefix}{command}  {desc}")
    return "\n".join(lines)


def render_main(version: str, prefix: str = "/") -> str:
    return _render_grouped(
        f"恶魔bot {version} 常用指令\n前缀：/ 或 ==\n\n不常用/管理指令：{prefix}其他指令",
        MAIN_MENU,
        prefix,
    )


