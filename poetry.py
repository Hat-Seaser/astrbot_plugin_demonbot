# 这些词只用于决定“诗意池”，不调用模型。
KEYWORDS = {
    "sad": ("不顺", "烦", "难过", "失落", "委屈", "心累", "低落", "伤心"),
    "longing": ("想念", "想你", "想主人", "好久没见", "好久没说话", "等你", "牵挂", "思念"),
    "night": ("晚安", "晚上", "深夜", "夜里", "睡不着", "月亮", "月色"),
    "hopeful": ("前程", "加油", "努力", "坚持", "未来", "机会", "重新开始"),
    "friendship": ("朋友", "兄弟", "姐妹", "知己", "一起", "同学"),
    "celebration": ("生日", "礼物", "惊喜", "庆祝", "开心", "高兴"),
}


def _pool_for_text(text: str) -> str:
    t = (text or "").strip()
    for pool, words in KEYWORDS.items():
        if any(w in t for w in words):
            return pool
    return "general"


def is_poetry_worthy(text: str) -> bool:
    t = (text or "").strip()
    if not t or len(t) > 40:
        return False
    return _pool_for_text(t) != "general"


def pick_poem(context: str | None = None) -> str:
    """按上下文选择诗句；不传 context 时保留全局随机行为。"""
    if context:
        pool = POETRY_POOLS.get(context, POETRY_POOLS["general"])
    else:
        pool = POETRY_POOLS["general"]
    return random.choice(pool)


def pick_for_context(context: str) -> str:
    """供插件场景调用。主人久未发言固定进入相思/牵挂语义池。"""
    if context == "idle_owner":
        return pick_poem("longing")
    return pick_poem(context)
